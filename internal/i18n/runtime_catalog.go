func Choose(portuguese string, english string) string {
	if Default() == EnglishUS {
		return english
	}
	return portuguese
}

// Text translates a complete user-facing or log message. Portuguese remains
// the compatibility fallback whenever a phrase has not yet been cataloged.
func Text(portuguese string) string {
	if Default() != EnglishUS {
		return portuguese
	}
	if translated, exists := englishText[portuguese]; exists {
		return translated
	}
	result := portuguese
	for _, replacement := range englishReplacements {
		result = strings.ReplaceAll(result, replacement.portuguese, replacement.english)
	}
	return result
}
